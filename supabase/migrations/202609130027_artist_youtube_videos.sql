create table public.youtube_channels (
  youtube_channel_id text primary key
    check (youtube_channel_id ~ '^UC[A-Za-z0-9_-]{22}$'),
  title text not null check (char_length(btrim(title)) between 1 and 300),
  thumbnail_url text,
  uploads_playlist_id text,
  channel_type text not null default 'unknown'
    check (channel_type in ('artist', 'label', 'vevo', 'publisher', 'unknown')),
  verification_status text not null default 'candidate'
    check (verification_status in ('candidate', 'verified', 'rejected')),
  last_refreshed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.artist_youtube_channels (
  artist_id bigint not null references public.artists(id) on delete cascade,
  youtube_channel_id text not null references public.youtube_channels(youtube_channel_id) on delete cascade,
  match_method text not null
    check (match_method in ('wikidata', 'youtube_search', 'manual')),
  confidence_score double precision not null default 0
    check (confidence_score between 0 and 1),
  match_evidence jsonb not null default '{}'::jsonb
    check (jsonb_typeof(match_evidence) = 'object'),
  status text not null default 'candidate'
    check (status in ('candidate', 'verified', 'rejected')),
  reviewed_by uuid references public.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (artist_id, youtube_channel_id)
);

create table public.youtube_videos (
  id bigint generated by default as identity primary key,
  youtube_video_id text not null unique
    check (youtube_video_id ~ '^[A-Za-z0-9_-]{11}$'),
  youtube_channel_id text not null references public.youtube_channels(youtube_channel_id) on delete restrict,
  title text not null check (char_length(btrim(title)) between 1 and 500),
  thumbnail_url text,
  channel_title text not null check (char_length(btrim(channel_title)) between 1 and 300),
  view_count bigint not null default 0 check (view_count >= 0),
  published_at timestamptz,
  duration_seconds integer check (duration_seconds is null or duration_seconds >= 0),
  is_embeddable boolean not null default false,
  availability_status text not null default 'available'
    check (availability_status in ('available', 'unavailable')),
  last_refreshed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.artist_videos (
  id bigint generated by default as identity primary key,
  artist_id bigint not null references public.artists(id) on delete cascade,
  youtube_video_id text not null references public.youtube_videos(youtube_video_id) on delete cascade,
  matched_track_id bigint references public.tracks(id) on delete set null,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  is_official boolean not null default false,
  confidence_score double precision not null default 0
    check (confidence_score between 0 and 1),
  match_evidence jsonb not null default '{}'::jsonb
    check (jsonb_typeof(match_evidence) = 'object'),
  reviewed_by uuid references public.users(id) on delete set null,
  reviewed_at timestamptz,
  rejection_reason text
    check (rejection_reason is null or char_length(btrim(rejection_reason)) between 1 and 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (artist_id, youtube_video_id),
  check (status <> 'rejected' or rejection_reason is not null)
);

create index artist_videos_public_idx
