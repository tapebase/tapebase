create or replace function public.queue_artist_youtube_sync()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.catalog_visible = true and new.spotify_id is not null then
    insert into public.artist_youtube_sync(artist_id)
    values (new.id)
    on conflict (artist_id) do nothing;
  end if;
  return new;
end;
$$;

create trigger artists_queue_youtube_sync
after insert or update of catalog_visible, spotify_id on public.artists
for each row execute function public.queue_artist_youtube_sync();

insert into public.artist_youtube_sync(artist_id)
select id from public.artists
where catalog_visible = true and spotify_id is not null
on conflict (artist_id) do nothing;

create or replace function public.reserve_youtube_search_quota(
  requested_calls integer default 1,
  daily_limit integer default 50
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if requested_calls < 1 or requested_calls > 10
    or daily_limit < 1 or daily_limit > 100 then
    raise exception 'Invalid YouTube quota reservation';
  end if;

  insert into public.youtube_sync_daily_usage(usage_date, search_calls)
  values ((now() at time zone 'UTC')::date, requested_calls)
  on conflict (usage_date) do nothing;
  if found then return true; end if;

  update public.youtube_sync_daily_usage
  set search_calls = search_calls + requested_calls, updated_at = now()
  where usage_date = (now() at time zone 'UTC')::date
    and search_calls + requested_calls <= daily_limit;
  return found;
end;
$$;

create or replace function public.artist_videos_for_profile(
  target_artist_id bigint,
  result_limit integer default 5
)
returns table (
  youtube_video_id text,
  title text,
  thumbnail_url text,
  channel_title text,
  view_count bigint,
  published_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select video.youtube_video_id, video.title, video.thumbnail_url,
    video.channel_title, video.view_count, video.published_at
  from public.artist_videos relation
  join public.youtube_videos video
    on video.youtube_video_id = relation.youtube_video_id
  where relation.artist_id = target_artist_id
    and relation.status = 'approved'
    and video.availability_status = 'available'
    and video.is_embeddable = true
    and video.last_refreshed_at >= now() - interval '30 days'
  order by video.view_count desc, video.published_at desc nulls last, video.youtube_video_id
  limit least(greatest(coalesce(result_limit, 5), 1), 5);
$$;

create or replace function public.review_artist_youtube_video(
  target_artist_id bigint,
  target_youtube_video_id text,
  decision text,
  official boolean default false,
  reason text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  admin_id uuid := (select auth.uid());
  normalized_reason text := nullif(btrim(reason), '');
begin
  if admin_id is null or not public.is_catalog_admin() then
    raise exception 'Administrator access required';
  end if;
  if decision not in ('approve', 'reject') then
    raise exception 'Invalid video moderation decision';
  end if;
  if decision = 'reject' and normalized_reason is null then
    raise exception 'Rejection reason is required';
  end if;
  if normalized_reason is not null and char_length(normalized_reason) > 1000 then
    raise exception 'Rejection reason is too long';
  end if;

  update public.artist_videos
  set status = case when decision = 'approve' then 'approved' else 'rejected' end,
    is_official = case when decision = 'approve' then official else false end,
    rejection_reason = case when decision = 'reject' then normalized_reason else null end,
    reviewed_by = admin_id,
    reviewed_at = now()
  where artist_id = target_artist_id
    and youtube_video_id = target_youtube_video_id;
  if not found then raise exception 'Video candidate not found'; end if;
end;
$$;

create or replace function public.review_artist_youtube_channel(
  target_artist_id bigint,
  target_youtube_channel_id text,
  decision text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  admin_id uuid := (select auth.uid());
begin
  if admin_id is null or not public.is_catalog_admin() then
    raise exception 'Administrator access required';
  end if;
  if decision not in ('verify', 'reject') then
    raise exception 'Invalid channel moderation decision';
  end if;

  update public.artist_youtube_channels
  set status = case when decision = 'verify' then 'verified' else 'rejected' end,
    reviewed_by = admin_id,
    reviewed_at = now()
  where artist_id = target_artist_id
    and youtube_channel_id = target_youtube_channel_id;
  if not found then raise exception 'Channel candidate not found'; end if;

  if decision = 'verify' then
    update public.youtube_channels
    set verification_status = 'verified'
    where youtube_channel_id = target_youtube_channel_id;
    update public.artist_youtube_sync
    set status = 'pending', next_search_at = now(), last_error = null
    where artist_id = target_artist_id;
  end if;
end;
$$;

